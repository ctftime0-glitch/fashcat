#!/bin/bash

echo "install ollama"
command1=$(curl -fsSL https://ollama.com/install.sh | sh)
echo "####################################################################################"
echo "$command1"
echo "####################################################################################"

echo "check version"
command2=$(ollama --version)
echo "####################################################################################"
echo "$command2"
echo "####################################################################################"

echo "check models"
command3=$(ollama list)
echo "####################################################################################"
echo "$command3"
echo "####################################################################################"

echo "install model"
command4=$(ollama install qwen2.5-coder:3b )
echo "####################################################################################"
echo "$command4"
echo "####################################################################################"

echo "run ollama"
command5=$(ollama run qwen2.5-coder:3b)
echo "####################################################################################"
echo "$command5"
echo "####################################################################################"